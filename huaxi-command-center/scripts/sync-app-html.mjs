/**
 * 根据 config/app-shell.manifest.mjs 重写 app.html 中 APP_SHELL 区块
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  styles,
  backendScripts,
  reactEntry,
  mapScripts,
  enhanceScripts,
} from '../config/app-shell.manifest.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const appHtmlPath = path.join(root, 'app.html')

function tagLink(item) {
  const cross = item.crossorigin ? ' crossorigin' : ''
  return `    <link rel="stylesheet"${cross} href="${item.href}" />`
}

function tagScript(item) {
  const defer = item.defer ? ' defer' : ''
  const type = item.type ? ` type="${item.type}"` : ''
  const cross = item.crossorigin ? ' crossorigin ' : ' '
  const src = item.src
  if (item.type === 'module') {
    return `    <script${type}${cross}src="${src}"></script>`
  }
  return `    <script src="${src}"${defer}></script>`
}

function buildBlock() {
  const lines = []
  lines.push('    <!-- APP_SHELL:HEAD:START — generated by npm run sync:app-html -->')
  for (const s of styles) lines.push(tagLink(s))
  lines.push('    <!-- INJECT_BACKEND_ENV -->')
  for (const s of backendScripts) lines.push(tagScript(s))
  lines.push(`    <!-- ${reactEntry.comment} -->`)
  lines.push(tagScript(reactEntry))
  lines.push('    <!-- 协作三维地图由 command-map-page + map-hospital-glb 增强，勿与 map-medical-overlay 双开 -->')
  for (const s of mapScripts) lines.push(tagScript(s))
  for (const s of enhanceScripts) lines.push(tagScript(s))
  lines.push('    <!-- APP_SHELL:HEAD:END -->')
  return lines.join('\n')
}

const html = fs.readFileSync(appHtmlPath, 'utf8')
const start = '    <!-- APP_SHELL:HEAD:START'
const end = '    <!-- APP_SHELL:HEAD:END -->'

if (!html.includes('APP_SHELL:HEAD:START')) {
  console.error('app.html 缺少 APP_SHELL 标记，请先插入占位注释')
  process.exit(1)
}

const re = /    <!-- APP_SHELL:HEAD:START[\s\S]*?    <!-- APP_SHELL:HEAD:END -->/
const next = html.replace(re, buildBlock())
fs.writeFileSync(appHtmlPath, next, 'utf8')
console.log('Updated', appHtmlPath)
