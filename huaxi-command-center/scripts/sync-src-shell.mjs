/**
 * 根据 config/app-shell.manifest.mjs 重写 src-shell.html 中 SRC_SHELL 区块
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  styles,
  backendScripts,
  mapScripts,
  srcShellHomeEnhanceScripts,
} from '../config/app-shell.manifest.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const htmlPath = path.join(root, 'src-shell.html')

function tagLink(item) {
  const cross = item.crossorigin ? ' crossorigin' : ''
  return `    <link rel="stylesheet"${cross} href="${item.href}" />`
}

function tagScript(item) {
  const defer = item.defer ? ' defer' : ''
  return `    <script src="${item.src}"${defer}></script>`
}

function buildHeadBlock() {
  const lines = []
  lines.push('    <!-- SRC_SHELL:HEAD:START — generated by npm run sync:src-shell -->')
  for (const s of styles) lines.push(tagLink(s))
  lines.push('    <!-- INJECT_BACKEND_ENV -->')
  for (const s of backendScripts) lines.push(tagScript(s))
  lines.push('    <!-- 地图 + 侧栏（与 app.html 一致；React 地图走 /src/main.tsx） -->')
  for (const s of mapScripts) lines.push(tagScript(s))
  for (const s of srcShellHomeEnhanceScripts) lines.push(tagScript(s))
  lines.push('    <!-- SRC_SHELL:HEAD:END -->')
  return lines.join('\n')
}

let html = fs.readFileSync(htmlPath, 'utf8')
const re = /    <!-- SRC_SHELL:HEAD:START[\s\S]*?    <!-- SRC_SHELL:HEAD:END -->/
if (!re.test(html)) {
  console.error('src-shell.html 缺少 SRC_SHELL:HEAD 标记')
  process.exit(1)
}
html = html.replace(re, buildHeadBlock())
fs.writeFileSync(htmlPath, html, 'utf8')
console.log('Updated', htmlPath)
